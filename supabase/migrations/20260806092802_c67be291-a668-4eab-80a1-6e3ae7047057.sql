CREATE TYPE public.commande_statut AS ENUM ('a_commander','commandee','recue_partiellement','recue','cloturee');

CREATE TABLE public.commandes_achat (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  numero bigint GENERATED BY DEFAULT AS IDENTITY,
  etablissement_id uuid NOT NULL REFERENCES public.etablissements(id) ON DELETE CASCADE,
  magasin_id uuid REFERENCES public.magasins(id) ON DELETE SET NULL,
  fournisseur text NOT NULL,
  statut public.commande_statut NOT NULL DEFAULT 'a_commander',
  demandeur_id uuid REFERENCES public.profils_utilisateurs(id) ON DELETE SET NULL,
  date_commande timestamp with time zone,
  montant_estime numeric,
  reference text,
  notes text,
  pieces_jointes text[] NOT NULL DEFAULT '{}',
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now()
);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.commandes_achat TO authenticated;
GRANT ALL ON public.commandes_achat TO service_role;
