CREATE OR REPLACE FUNCTION public.can_manage_commande(_user_id uuid, _commande_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.commandes_achat c
    WHERE c.id = _commande_id AND public.can_manage_stock(_user_id, c.etablissement_id)
  );
$$;

CREATE TABLE public.commandes_achat_lignes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  commande_id uuid NOT NULL REFERENCES public.commandes_achat(id) ON DELETE CASCADE,
  piece_id uuid NOT NULL REFERENCES public.pieces(id) ON DELETE RESTRICT,
  quantite_commandee numeric NOT NULL CHECK (quantite_commandee > 0),
  quantite_recue numeric NOT NULL DEFAULT 0 CHECK (quantite_recue >= 0),
  prix_unitaire numeric,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  UNIQUE (commande_id, piece_id)
);

