CREATE OR REPLACE FUNCTION public.commande_refresh_statut()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  _cid uuid;
  _total numeric;
  _recu numeric;
  _statut public.commande_statut;
BEGIN
  _cid := COALESCE(NEW.commande_id, OLD.commande_id);
  SELECT COALESCE(sum(quantite_commandee),0), COALESCE(sum(quantite_recue),0)
    INTO _total, _recu
    FROM public.commandes_achat_lignes WHERE commande_id = _cid;

  SELECT statut INTO _statut FROM public.commandes_achat WHERE id = _cid;
  IF _statut = 'cloturee' THEN RETURN COALESCE(NEW, OLD); END IF;

  IF _recu <= 0 THEN
    IF _statut IN ('recue','recue_partiellement') THEN
      UPDATE public.commandes_achat SET statut = 'commandee' WHERE id = _cid;
    END IF;
  ELSIF _recu >= _total THEN
    UPDATE public.commandes_achat SET statut = 'recue' WHERE id = _cid;
  ELSE
    UPDATE public.commandes_achat SET statut = 'recue_partiellement' WHERE id = _cid;
  END IF;

  RETURN COALESCE(NEW, OLD);
END;
$$;

CREATE TRIGGER trg_commande_refresh_statut
AFTER INSERT OR UPDATE OF quantite_recue, quantite_commandee OR DELETE ON public.commandes_achat_lignes
FOR EACH ROW EXECUTE FUNCTION public.commande_refresh_statut();

CREATE OR REPLACE FUNCTION public.reception_commande(
  _commande_id uuid,
  _magasin_id uuid,
  _lignes jsonb
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  _item jsonb;
  _ligne_id uuid;
  _qte numeric;
  _piece uuid;
  _restant numeric;
  _numero bigint;
BEGIN
  IF NOT public.can_manage_commande(auth.uid(), _commande_id) THEN
    RAISE EXCEPTION 'Accès refusé à cette commande';
  END IF;
  IF _magasin_id IS NULL THEN
    RAISE EXCEPTION 'Magasin de destination obligatoire';
  END IF;

  SELECT numero INTO _numero FROM public.commandes_achat WHERE id = _commande_id;

  FOR _item IN SELECT * FROM jsonb_array_elements(_lignes)
  LOOP
    _ligne_id := (_item->>'ligne_id')::uuid;
    _qte := COALESCE((_item->>'quantite')::numeric, 0);
    IF _qte <= 0 THEN CONTINUE; END IF;

    SELECT piece_id, quantite_commandee - quantite_recue
      INTO _piece, _restant
      FROM public.commandes_achat_lignes
     WHERE id = _ligne_id AND commande_id = _commande_id;

    IF _piece IS NULL THEN
      RAISE EXCEPTION 'Ligne de commande introuvable';
    END IF;
    IF _qte > _restant THEN
      RAISE EXCEPTION 'Quantité reçue supérieure au reste à recevoir';
    END IF;

    UPDATE public.commandes_achat_lignes
       SET quantite_recue = quantite_recue + _qte
     WHERE id = _ligne_id;

    INSERT INTO public.stock_mouvements
      (piece_id, magasin_id, type, quantite, origine, etat_piece, user_id, reference, justification)
    VALUES
      (_piece, _magasin_id, 'entree', _qte, 'commande_achat', 'neuf', auth.uid(),
       'CMD-' || COALESCE(_numero::text, ''), 'Réception commande d''achat');
  END LOOP;
END;
$$;

GRANT EXECUTE ON FUNCTION public.reception_commande(uuid, uuid, jsonb) TO authenticated;
GRANT EXECUTE ON FUNCTION public.can_manage_commande(uuid, uuid) TO authenticated;